/**
 * Calculates current Player's Combat Power rating based on live stats, level, and achievements
 */
export function calculatePlayerPower(player: Player, totalVolumeKg: number): number {
  const base = player.level * 1000 + player.xp;
  const statWeight =
    player.stats.STR * 35 +
    player.stats.VIT * 25 +
    player.stats.AGI * 25 +
    player.stats.INT * 20 +
    player.stats.PER * 30;
  const volumeBonus = Math.round(totalVolumeKg * 0.4);
  const streakBonus = player.streakDays * 150;
  return base + statWeight + volumeBonus + streakBonus;
}

/**
 * Converts live player state into a Leaderboard entry
 */
export function createPlayerLeaderboardEntry(
  player: Player,
  workouts: WorkoutLog[],
  steps: StepsData,
  achievements: Achievement[]
): HunterLeaderboardEntry {
  const totalVolume = workouts.reduce((acc, w) => acc + (w.totalVolumeKg || 0), 0);
  const power = calculatePlayerPower(player, totalVolume);
  const unlockedShadows = achievements.filter((a) => a.unlocked).length;

  return {
    id: 'player-current',
    name: `${player.name} (YOU)`,
    title: player.title,
    rank: player.rank,
    guild: 'Ahjin Guild Candidate',
    hunterClass: player.hunterClass || 'Shadow Monarch Candidate',
    avatar: player.avatar || 'shadow-monarch',
    level: player.level,
    xp: player.xp,
    powerRating: power,
    workoutVolumeKg: totalVolume,
    streakDays: player.streakDays,
    dungeonFloor: steps.dungeonFloor || 14,
    shadowsCount: unlockedShadows,
    respectCount: 520,
    recentFeat: `${player.streakDays}-Day Gate Streak • Level ${player.level} Awakened`,
    bio: player.bio || 'Rising through the Hunter ranks one dungeon at a time.',
    bestLift: totalVolume > 0 ? `Compound Max Volume: ${Math.round(totalVolume * 0.25)}kg` : 'Calibration in progress',
    stats: player.stats,
    rankChange: 2,
    isPlayer: true,
  };
}

/**
 * Sorts and ranks hunters according to chosen category
 */
export function getRankedHunters(
  hunters: HunterLeaderboardEntry[],
  category: LeaderboardCategory
): HunterLeaderboardEntry[] {
  const sorted = [...hunters].sort((a, b) => {
    switch (category) {
      case 'power':
        return b.powerRating - a.powerRating;
      case 'volume':
        return b.workoutVolumeKg - a.workoutVolumeKg;
      case 'streak':
        return b.streakDays - a.streakDays;
      case 'floor':
        return b.dungeonFloor - a.dungeonFloor;
      case 'shadows':
        return b.shadowsCount - a.shadowsCount;
      default:
        return b.powerRating - a.powerRating;
    }
  });

  return sorted;
}

